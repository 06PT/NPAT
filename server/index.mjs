import express from 'express';
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { handleGame } from '../lib/game/service.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const dataDir=resolve(process.env.DATA_DIR||resolve(root,'data'));
mkdirSync(dataDir,{recursive:true});
const db=new DatabaseSync(resolve(dataDir,'rooms.sqlite'));
db.exec('PRAGMA journal_mode = WAL');
db.exec('CREATE TABLE IF NOT EXISTS game_rooms (code TEXT PRIMARY KEY, state TEXT NOT NULL, revision INTEGER NOT NULL, expires INTEGER NOT NULL)');
db.exec('CREATE INDEX IF NOT EXISTS idx_game_rooms_expires ON game_rooms(expires)');
const get=db.prepare('SELECT state FROM game_rooms WHERE code = ? AND expires > ?');
const insert=db.prepare('INSERT OR IGNORE INTO game_rooms (code, state, revision, expires) VALUES (?, ?, ?, ?)');
const update=db.prepare('UPDATE game_rooms SET state = ?, revision = ? WHERE code = ? AND revision = ?');
const store={get:async code=>{const row=get.get(code,Date.now());return row?JSON.parse(row.state):null;},insert:async room=>insert.run(room.code,JSON.stringify(room),room.revision,room.expires).changes===1,compareAndSet:async(room,revision)=>update.run(JSON.stringify(room),room.revision,room.code,revision).changes===1};
const app=express();
app.disable('x-powered-by');
if(process.env.TRUST_PROXY)app.set('trust proxy',Number(process.env.TRUST_PROXY));
app.use(express.json({limit:'8kb'}));
app.use((_req,res,next)=>{res.set({'X-Content-Type-Options':'nosniff','Referrer-Policy':'same-origin','X-Frame-Options':'SAMEORIGIN'});next();});
const limits=new Map();
const cleanup=setInterval(()=>{db.prepare('DELETE FROM game_rooms WHERE expires < ?').run(Date.now());for(const[key,value]of limits)if(value.until<Date.now())limits.delete(key);},60000);cleanup.unref();
app.get('/health',(_req,res)=>res.json({status:'ok'}));
app.post('/api/game',async(req,res)=>{
 res.set('Cache-Control','no-store');
 const origin=req.get('origin'),allowedOrigin=process.env.PUBLIC_ORIGIN||`${req.protocol}://${req.get('host')}`;
 if(origin&&origin!==allowedOrigin)return res.status(403).json({error:'Cross-site requests are not allowed.'});
 const key=req.ip,rate=limits.get(key);const r=rate&&rate.until>Date.now()?rate:{count:0,entry:0,until:Date.now()+60000};r.count++;if(['create','join'].includes(req.body?.action))r.entry++;limits.set(key,r);
 if(r.count>3000||r.entry>30)return res.status(429).json({error:'Too many requests. Please wait a minute.'});
 try{return res.json(await handleGame(store,req.body,req.get('x-player-token')||''));}catch(error){if(!error.status)console.error(error);return res.status(error.status||503).json({error:error.status?error.message:'The game service is unavailable. Please retry.'});}
});
app.use(express.static(resolve(root,'web-dist'),{index:false}));
app.get(['/', '/room/:code'],(_req,res)=>res.sendFile(resolve(root,'web-dist/index.html')));
app.use((_req,res)=>res.status(404).json({error:'Not found'}));
app.use((error,_req,res,_next)=>res.status(error.status||500).json({error:error.status===413?'Request too large.':'Invalid request.'}));
const server=app.listen(Number(process.env.PORT ?? 3000),'0.0.0.0',()=>console.log(`Game running on port ${server.address().port}`));
for(const signal of ['SIGTERM','SIGINT'])process.on(signal,()=>server.close(()=>{db.close();process.exit(0);}));
